-- Ejecuta este archivo en Supabase > SQL Editor > New query.
create table if not exists public.ideas (
  id bigint generated by default as identity primary key,
  name text not null default 'Una persona del equipo',
  message text not null check (char_length(message) between 4 and 280),
  created_at timestamptz not null default now()
);

alter table public.ideas enable row level security;

-- Permite a cualquier persona ver ideas y publicar una nueva, sin iniciar sesión.
create policy "Anyone can read ideas"
on public.ideas for select
to anon, authenticated
using (true);

create policy "Anyone can add ideas"
on public.ideas for insert
to anon, authenticated
with check (
  char_length(message) between 4 and 280
  and char_length(name) <= 40
);

-- Actualizaciones en vivo para que las flores aparezcan en otros dispositivos.
alter publication supabase_realtime add table public.ideas;
